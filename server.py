#!/usr/bin/env python3
"""
server.py - HTTP + WebSocket server for Duet Helper.

Layout:
    client/                 static client files (served at /)
    output/<name>/          generated tracks (served at /output/<name>/...)
    uploads/                temporary uploaded source audio
    voice-sep/              separation pipeline and model weights

HTTP API:
    GET    /                          client/index.html
    GET    /<path>                    any file from client/
    GET    /output/<name>/<path>      file from output/<name>/
    GET    /output/<name>/index.json  generated track manifest
    GET    /api/ws                    WebSocket state/progress stream
    POST   /api/output/<name>         upload source audio and queue processing
    PUT    /api/output/<name>         same as POST
    PUSH   /api/output/<name>         same as POST
    DELETE /api/output/<name>         stop processing and delete output

WebSocket messages (JSON):
    {"type": "state",    "outputs": [...]}
    {"type": "add",      "output": {...}}
    {"type": "update",   "output": {...}}
    {"type": "progress", "name": "...", "progress": {...}, "status": "..."}
    {"type": "delete",   "name": "..."}

Run:
    .venv/bin/python server.py --host 0.0.0.0 --port 8000
"""

from __future__ import annotations

import argparse
import asyncio
import json
import logging
import mimetypes
import os
import re
import shutil
import sys
import threading
import time
import traceback
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from urllib.parse import quote

from aiohttp import WSMsgType, web

BASE_DIR = Path(__file__).resolve().parent
CLIENT_DIR = BASE_DIR / "client"
OUTPUT_DIR = BASE_DIR / "output"
UPLOAD_DIR = BASE_DIR / "uploads"
VOICE_SEP_DIR = BASE_DIR / "voice-sep"
MODEL_DIR = VOICE_SEP_DIR / "models"

# voice-sep/ contains a hyphen, so import it as a plain module from sys.path.
if str(VOICE_SEP_DIR) not in sys.path:
    sys.path.insert(0, str(VOICE_SEP_DIR))
import voice_sep  # noqa: E402

logger = logging.getLogger("duet-helper")

CONFIG: dict[str, Any] = {
    "device": "cpu",
    "threads": max(1, (os.cpu_count() or 4) - 1),
    "demucs_model": "htdemucs",
    "chunk_seconds": 10.0,
    "overlap_seconds": 1.0,
}


# --------------------------------------------------------------------------
# state
# --------------------------------------------------------------------------

@dataclass
class Output:
    name: str
    status: str  # queued | processing | deleting | complete | error | incomplete
    progress: dict[str, Any] | None = None
    error: str | None = None
    meta: dict[str, Any] | None = None
    created: float = 0.0
    updated: float = 0.0


@dataclass
class Job:
    name: str
    input_path: Path
    cancel: threading.Event = field(default_factory=threading.Event)
    status: str = "queued"
    progress: dict[str, Any] | None = None
    last_emit: float = 0.0


outputs: dict[str, Output] = {}
jobs: dict[str, Job] = {}
clients: set[web.WebSocketResponse] = set()

job_queue: asyncio.Queue[str] | None = None
broadcast_lock: asyncio.Lock | None = None
loop: asyncio.AbstractEventLoop | None = None

_model = None
_model_lock = threading.Lock()


def _q(value: str) -> str:
    return quote(value, safe="")


def _validate_name(raw: str) -> str:
    name = raw.strip()
    if not name:
        raise ValueError("output name is empty")
    if name in (".", "..") or name.startswith("."):
        raise ValueError("output name may not start with '.'")
    if any(ch in name for ch in "/\\\0"):
        raise ValueError("output name may not contain path separators")
    if len(name) > 200:
        raise ValueError("output name is too long")
    return name


def _read_meta(name: str) -> dict[str, Any] | None:
    path = OUTPUT_DIR / name / "diarization.json"
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return None


def _file_sort_key(name: str) -> tuple[int, str]:
    order = [
        "instrumental.wav",
        "singer_1.wav",
        "singer_2.wav",
        "diarization.json",
    ]
    try:
        return (order.index(name), name)
    except ValueError:
        return (len(order), name)


def _scan_files(name: str) -> list[dict[str, Any]]:
    directory = OUTPUT_DIR / name
    if not directory.is_dir():
        return []

    files: list[dict[str, Any]] = []
    for path in sorted(directory.iterdir(), key=lambda p: _file_sort_key(p.name)):
        if not path.is_file() or path.name.startswith("."):
            continue
        # index.json is generated by the server and is not a real output file.
        if path.name == "index.json":
            continue
        try:
            stat = path.stat()
        except OSError:
            continue
        files.append({
            "name": path.name,
            "url": f"/output/{_q(name)}/{_q(path.name)}",
            "size": stat.st_size,
            "mtime": stat.st_mtime,
        })
    return files


def _snapshot(name: str) -> dict[str, Any] | None:
    out = outputs.get(name)
    if out is None:
        return None
    meta = _read_meta(name) or out.meta
    return {
        "name": out.name,
        "status": out.status,
        "progress": out.progress,
        "error": out.error,
        "meta": meta,
        "files": _scan_files(out.name),
        "index": f"/output/{_q(out.name)}/index.json",
        "created": out.created,
        "updated": out.updated,
    }


def _state_message() -> dict[str, Any]:
    return {
        "type": "state",
        "outputs": [snap for name in sorted(outputs)
                    if (snap := _snapshot(name)) is not None],
    }


def scan_outputs() -> None:
    """Populate state from directories already present on disk."""
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for directory in OUTPUT_DIR.iterdir():
        if not directory.is_dir() or directory.name.startswith("."):
            continue
        if directory.name in jobs:
            continue

        meta = _read_meta(directory.name)
        status = "complete" if meta is not None else "incomplete"
        if meta is not None:
            progress = {
                "stage": "done",
                "fraction": 1.0,
                "overall": 1.0,
                "message": "Complete",
            }
        else:
            progress = {
                "stage": "incomplete",
                "fraction": 0.0,
                "overall": 0.0,
                "message": "Output is incomplete",
            }

        try:
            created = directory.stat().st_ctime
            mtimes = [p.stat().st_mtime for p in directory.iterdir() if p.is_file()]
            updated = max(mtimes, default=created)
        except OSError:
            created = updated = time.time()

        outputs[directory.name] = Output(
            name=directory.name,
            status=status,
            progress=progress,
            meta=meta,
            created=created,
            updated=updated,
        )


# --------------------------------------------------------------------------
# websocket broadcast
# --------------------------------------------------------------------------

async def broadcast(message: dict[str, Any]) -> None:
    if not clients:
        return
    assert broadcast_lock is not None
    async with broadcast_lock:
        dead: list[web.WebSocketResponse] = []
        for ws in list(clients):
            if ws.closed:
                dead.append(ws)
                continue
            try:
                await ws.send_json(message)
            except Exception:
                dead.append(ws)
        for ws in dead:
            clients.discard(ws)


def _apply_progress(name: str, info: dict[str, Any]) -> None:
    out = outputs.get(name)
    if out is None:
        return
    out.progress = info
    out.updated = time.time()
    asyncio.create_task(broadcast({
        "type": "progress",
        "name": name,
        "status": out.status,
        "progress": info,
    }))


# --------------------------------------------------------------------------
# pipeline worker
# --------------------------------------------------------------------------

def _ensure_model():
    global _model
    with _model_lock:
        if _model is None:
            logger.info("Loading MedleyVox model from %s", MODEL_DIR)
            _model = voice_sep.load_model(MODEL_DIR, CONFIG["device"])
        return _model


def _run_job(job: Job) -> dict[str, Any]:
    outdir = OUTPUT_DIR / job.name
    outdir.mkdir(parents=True, exist_ok=True)

    def on_progress(info: dict[str, Any]) -> None:
        job.progress = info
        now = time.monotonic()
        # Demucs emits a callback per segment; throttle the websocket a little.
        if info.get("stage") == "done" or now - job.last_emit >= 0.1:
            job.last_emit = now
            assert loop is not None
            loop.call_soon_threadsafe(_apply_progress, job.name, info)

    model = _ensure_model()
    return voice_sep.run_pipeline(
        job.input_path,
        outdir,
        demucs_model=CONFIG["demucs_model"],
        device=CONFIG["device"],
        model_dir=MODEL_DIR,
        chunk_seconds=CONFIG["chunk_seconds"],
        overlap_seconds=CONFIG["overlap_seconds"],
        keep_stems=False,
        threads=CONFIG["threads"],
        model=model,
        on_progress=on_progress,
        should_cancel=job.cancel.is_set,
    )


async def _remove_output(name: str, *, announce: bool = True) -> None:
    job = jobs.pop(name, None)
    if job is not None:
        job.cancel.set()
        job.input_path.unlink(missing_ok=True)

    outputs.pop(name, None)
    target = OUTPUT_DIR / name
    if target.exists():
        await asyncio.to_thread(shutil.rmtree, target, True)

    if announce:
        await broadcast({"type": "delete", "name": name})


async def _worker() -> None:
    assert job_queue is not None
    while True:
        name = await job_queue.get()
        job = jobs.get(name)
        try:
            if job is None or job.cancel.is_set():
                continue

            job.status = "processing"
            out = outputs.get(name)
            if out is not None:
                out.status = "processing"
                out.progress = {
                    "stage": "prepare",
                    "fraction": 0.0,
                    "overall": 0.0,
                    "message": "Starting",
                }
                out.updated = time.time()
            logger.info("Processing %s", name)
            await broadcast({"type": "update", "output": _snapshot(name)})

            try:
                meta = await asyncio.to_thread(_run_job, job)
                if job.cancel.is_set():
                    raise voice_sep.Cancelled()

                out = outputs.get(name)
                if out is not None:
                    out.status = "complete"
                    out.error = None
                    out.meta = meta
                    out.progress = {
                        "stage": "done",
                        "fraction": 1.0,
                        "overall": 1.0,
                        "message": "Complete",
                    }
                    out.updated = time.time()
                logger.info("Completed %s in %.1fs",
                            name, meta.get("elapsed_seconds") or 0.0)
                await broadcast({"type": "update", "output": _snapshot(name)})
            except voice_sep.Cancelled:
                logger.info("Cancelled %s", name)
                await _remove_output(name)
            except Exception as exc:
                logger.error("Job %s failed: %s\n%s", name, exc,
                             traceback.format_exc())
                out = outputs.get(name)
                if out is not None:
                    out.status = "error"
                    out.error = f"{type(exc).__name__}: {exc}"
                    out.progress = {
                        "stage": "error",
                        "fraction": 0.0,
                        "overall": 0.0,
                        "message": out.error,
                    }
                    out.updated = time.time()
                await broadcast({"type": "update", "output": _snapshot(name)})
        finally:
            if job is not None:
                jobs.pop(name, None)
                job.input_path.unlink(missing_ok=True)
            job_queue.task_done()


# --------------------------------------------------------------------------
# upload helpers
# --------------------------------------------------------------------------

_EXTRA_TYPES = {
    "audio/mpeg": ".mp3",
    "audio/mp3": ".mp3",
    "audio/wav": ".wav",
    "audio/x-wav": ".wav",
    "audio/wave": ".wav",
    "audio/flac": ".flac",
    "audio/x-flac": ".flac",
    "audio/ogg": ".ogg",
    "audio/opus": ".opus",
    "audio/webm": ".webm",
    "audio/mp4": ".m4a",
    "audio/aac": ".aac",
    "audio/x-m4a": ".m4a",
}


def _upload_extension(request: web.Request, content_type: str) -> str:
    disposition = request.headers.get("Content-Disposition", "")
    match = re.search(r'filename="?([^";]+)', disposition)
    if match:
        ext = Path(match.group(1)).suffix
        if ext:
            return ext.lower()

    if content_type in _EXTRA_TYPES:
        return _EXTRA_TYPES[content_type]
    ext = mimetypes.guess_extension(content_type) or ""
    return ext.lower()


async def _save_upload(request: web.Request, name: str) -> tuple[Path, str, int]:
    content_type = (request.content_type or "application/octet-stream")
    content_type = content_type.split(";", 1)[0].strip().lower()
    extension = _upload_extension(request, content_type)
    UPLOAD_DIR.mkdir(parents=True, exist_ok=True)

    if content_type.startswith("multipart/"):
        reader = await request.multipart()
        while True:
            part = await reader.next()
            if part is None:
                break
            if part.name not in ("file", "audio", "upload") and not part.filename:
                continue
            if part.filename:
                extension = Path(part.filename).suffix.lower() or extension
            path = UPLOAD_DIR / f"{name}{extension}"
            size = 0
            with open(path, "wb") as fh:
                while True:
                    chunk = await part.read_chunk(1 << 20)
                    if not chunk:
                        break
                    fh.write(chunk)
                    size += len(chunk)
            return path, part.filename or path.name, size
        raise web.HTTPBadRequest(text="multipart body contains no file part")

    path = UPLOAD_DIR / f"{name}{extension}"
    size = 0
    with open(path, "wb") as fh:
        async for chunk in request.content.iter_chunked(1 << 20):
            fh.write(chunk)
            size += len(chunk)
    return path, path.name, size


# --------------------------------------------------------------------------
# HTTP handlers
# --------------------------------------------------------------------------

async def client_file(request: web.Request) -> web.StreamResponse:
    rel = request.match_info.get("path", "")
    if rel in ("", "/"):
        rel = "index.html"

    target = (CLIENT_DIR / rel).resolve()
    root = CLIENT_DIR.resolve()
    if not target.is_relative_to(root) or not target.is_file():
        raise web.HTTPNotFound()
    return web.FileResponse(target)


async def output_file(request: web.Request) -> web.StreamResponse:
    try:
        name = _validate_name(request.match_info["filename"])
    except ValueError:
        raise web.HTTPNotFound()

    rel = request.match_info.get("path", "")
    if not rel:
        raise web.HTTPNotFound()

    directory = OUTPUT_DIR / name
    if not directory.is_dir():
        raise web.HTTPNotFound()

    if rel == "index.json":
        return web.json_response(build_index(name))

    target = (directory / rel).resolve()
    root = directory.resolve()
    if not target.is_relative_to(root) or not target.is_file():
        raise web.HTTPNotFound()
    return web.FileResponse(target)


async def push_output(request: web.Request) -> web.Response:
    try:
        name = _validate_name(request.match_info["filename"])
    except ValueError as exc:
        raise web.HTTPBadRequest(text=str(exc))

    if name in jobs:
        raise web.HTTPConflict(text=f"{name!r} is already queued or processing")

    try:
        input_path, original_name, size = await _save_upload(request, name)
    except web.HTTPException:
        raise
    except Exception as exc:
        raise web.HTTPBadRequest(text=f"Could not read upload: {exc}")

    if size <= 0:
        input_path.unlink(missing_ok=True)
        raise web.HTTPBadRequest(text="Empty upload")

    # Re-pushing a name replaces an existing completed/error output.
    existing = OUTPUT_DIR / name
    if existing.exists():
        await asyncio.to_thread(shutil.rmtree, existing, True)
    outputs.pop(name, None)
    existing.mkdir(parents=True, exist_ok=True)

    now = time.time()
    progress = {
        "stage": "queued",
        "fraction": 0.0,
        "overall": 0.0,
        "message": "Queued",
    }
    outputs[name] = Output(
        name=name,
        status="queued",
        progress=progress,
        created=now,
        updated=now,
    )
    jobs[name] = Job(
        name=name,
        input_path=input_path,
        status="queued",
        progress=progress,
    )

    assert job_queue is not None
    await job_queue.put(name)
    logger.info("Queued %s (%s, %.1f MiB)", name, original_name, size / 2**20)
    await broadcast({"type": "add", "output": _snapshot(name)})

    return web.json_response({
        "name": name,
        "status": "queued",
        "input": original_name,
        "size": size,
    }, status=202)


async def delete_output(request: web.Request) -> web.Response:
    try:
        name = _validate_name(request.match_info["filename"])
    except ValueError as exc:
        raise web.HTTPBadRequest(text=str(exc))

    job = jobs.get(name)
    if job is not None:
        if job.status == "queued":
            job.cancel.set()
            await _remove_output(name)
            logger.info("Deleted queued output %s", name)
            return web.json_response({"name": name, "status": "deleted"})

        # Processing: ask the worker to stop; it removes the output afterwards.
        job.cancel.set()
        out = outputs.get(name)
        if out is not None:
            out.status = "deleting"
            out.progress = {
                "stage": "deleting",
                "fraction": 0.0,
                "overall": 0.0,
                "message": "Stopping",
            }
            out.updated = time.time()
            await broadcast({"type": "update", "output": _snapshot(name)})
        logger.info("Cancelling %s", name)
        return web.json_response({"name": name, "status": "cancelling"},
                                 status=202)

    if name not in outputs and not (OUTPUT_DIR / name).exists():
        raise web.HTTPNotFound(text=f"No output named {name!r}")

    await _remove_output(name)
    logger.info("Deleted output %s", name)
    return web.json_response({"name": name, "status": "deleted"})


async def ws_handler(request: web.Request) -> web.WebSocketResponse:
    ws = web.WebSocketResponse(heartbeat=30)
    await ws.prepare(request)
    clients.add(ws)
    logger.info("WebSocket connected (%d clients)", len(clients))
    try:
        await ws.send_json(_state_message())
        async for msg in ws:
            if msg.type == WSMsgType.TEXT:
                try:
                    data = json.loads(msg.data)
                except ValueError:
                    continue
                if isinstance(data, dict) and data.get("type") in ("state", "refresh"):
                    await ws.send_json(_state_message())
            elif msg.type == WSMsgType.ERROR:
                break
    finally:
        clients.discard(ws)
        logger.info("WebSocket disconnected (%d clients)", len(clients))
    return ws


# --------------------------------------------------------------------------
# generated index
# --------------------------------------------------------------------------

_INDEX_LABELS = [
    ("instrumental.wav", "instrumental"),
    ("singer_1.wav", "singer 1"),
    ("singer_2.wav", "singer 2"),
]


def build_index(name: str) -> dict[str, Any]:
    """Generate the track manifest the client consumes."""
    directory = OUTPUT_DIR / name
    files: dict[str, str] = {}
    known: set[str] = set()

    for filename, label in _INDEX_LABELS:
        if (directory / filename).is_file():
            files[label] = f"/output/{_q(name)}/{_q(filename)}"
            known.add(filename)

    for path in sorted(directory.glob("*.wav")):
        if path.name not in known:
            files[path.stem] = f"/output/{_q(name)}/{_q(path.name)}"

    return {
        "name": name,
        "files": files,
        "meta": _read_meta(name),
    }


# --------------------------------------------------------------------------
# app lifecycle
# --------------------------------------------------------------------------

async def _on_startup(app: web.Application) -> None:
    global job_queue, broadcast_lock, loop
    loop = asyncio.get_running_loop()
    job_queue = asyncio.Queue()
    broadcast_lock = asyncio.Lock()
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
    scan_outputs()
    logger.info("Serving %d output(s) from %s", len(outputs), OUTPUT_DIR)
    app["worker"] = asyncio.create_task(_worker())


async def _on_cleanup(app: web.Application) -> None:
    for job in list(jobs.values()):
        job.cancel.set()
    task = app.get("worker")
    if task is not None:
        task.cancel()
        try:
            await task
        except asyncio.CancelledError:
            pass


def create_app() -> web.Application:
    mimetypes.add_type("text/javascript", ".mjs")
    mimetypes.add_type("audio/wav", ".wav")

    app = web.Application(client_max_size=4 * 1024**3)

    app.router.add_get("/api/ws", ws_handler)
    for method in ("POST", "PUT", "PUSH"):
        app.router.add_route(method, "/api/output/{filename}", push_output)
    app.router.add_delete("/api/output/{filename}", delete_output)
    app.router.add_get("/output/{filename}/{path:.*}", output_file)
    app.router.add_get("/", client_file)
    app.router.add_get("/{path:.*}", client_file)

    app.on_startup.append(_on_startup)
    app.on_cleanup.append(_on_cleanup)
    return app


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Serve the Duet Helper client and separation backend.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8000)
    parser.add_argument("--device", default="cpu", choices=["cpu", "cuda"])
    parser.add_argument("--threads", type=int,
                        default=max(1, (os.cpu_count() or 4) - 1))
    parser.add_argument("--demucs-model", default="htdemucs")
    parser.add_argument("--chunk-seconds", type=float, default=10.0)
    parser.add_argument("--overlap-seconds", type=float, default=1.0)
    parser.add_argument("--log-level", default="INFO",
                        choices=["DEBUG", "INFO", "WARNING", "ERROR"])
    args = parser.parse_args()

    logging.basicConfig(
        level=getattr(logging, args.log_level),
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )
    CONFIG.update({
        "device": args.device,
        "threads": args.threads,
        "demucs_model": args.demucs_model,
        "chunk_seconds": args.chunk_seconds,
        "overlap_seconds": args.overlap_seconds,
    })

    web.run_app(create_app(), host=args.host, port=args.port, print=None)


if __name__ == "__main__":
    main()
